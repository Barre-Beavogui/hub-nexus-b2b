function getCurrentLanguage() {
  return languageSelect.value || defaultLanguage;
}

function setFeedback(messageKey, state = "success") {
  const currentLanguage = getCurrentLanguage();
  feedback.textContent = translations[currentLanguage][messageKey];
  feedback.dataset.visible = "true";
  feedback.dataset.state = state;
  feedback.classList.toggle("is-error", state === "error");
}

function applyTranslations(language) {
  const dictionary = translations[language] || translations.fr;
  document.documentElement.lang = language;
  document.documentElement.dir = rtlLanguages.has(language) ? "rtl" : "ltr";
  document.body.classList.toggle("rtl", rtlLanguages.has(language));
  document.title = dictionary.documentTitle;

  textNodes.forEach((node) => {
    const key = node.dataset.i18n;
    if (dictionary[key]) {
      node.textContent = dictionary[key];
    }
  });

  placeholderNodes.forEach((node) => {
    const key = node.dataset.i18nPlaceholder;
    if (dictionary[key]) {
      node.setAttribute("placeholder", dictionary[key]);
    }
  });

  if (feedback.dataset.visible === "true") {
    const state = feedback.dataset.state || "success";
    const messageKey = state === "sending" ? "formSending" : state === "error" ? "formError" : "formSuccess";
    feedback.textContent = dictionary[messageKey];
  }

  if (languageSelect.value !== language) {
    languageSelect.value = language;
  }

  languageSelect.setAttribute("aria-label", dictionary.languageAriaLabel);

  window.localStorage.setItem("preferred-language", language);
}

languageSelect.addEventListener("change", (event) => {
  applyTranslations(event.target.value);
});

form.addEventListener("submit", (event) => {
  event.preventDefault();
  const formData = new FormData(form);

  submitButton.disabled = true;
  setFeedback("formSending", "sending");

  fetch(emailEndpoint, {
    method: "POST",
    body: formData,
    headers: {
      Accept: "application/json",
    },
  })
    .then((response) => {
      if (!response.ok) {
        throw new Error("ajax_submit_failed");
      }

      setFeedback("formSuccess", "success");
      form.reset();
    })
    .catch(() => {
      setFeedback("formError", "error");
      form.submit();
    })
    .finally(() => {
      submitButton.disabled = false;
    });
});

applyTranslations(defaultLanguage);
